const NAMES: Record<string, string> = Object.assign({}, ...THEME_GROUPS.map((g) => g.themes));

/** Nome leggibile di un tema (quelli nuovi non ancora tradotti restano in inglese, separati in parole). */
export function themeName(theme: string): string {
  return NAMES[theme] ?? theme.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase());
}
